-- Tracks approved AnyBike contact invitation email submissions.
-- Unique contact_id prevents repeated chargeable/marketing sends caused by double-clicks.
create table if not exists public.anybike_contact_invitation_email_log (
 id bigint generated by default as identity primary key,
 contact_id bigint not null references public.anybike_master_contacts(id),
 recipient text not null,
 invitation_type text not null check (invitation_type in ('dealer','private','both')),
 status text not null default 'sending' check (status in ('sending','submitted','failed')),
 provider_id text,
 error_message text,
 admin_id uuid not null,
 created_at timestamptz not null default now(),
 submitted_at timestamptz,
 unique(contact_id)
);
alter table public.anybike_contact_invitation_email_log enable row level security;
revoke all on public.anybike_contact_invitation_email_log from anon,authenticated;
grant select on public.anybike_contact_invitation_email_log to authenticated;
drop policy if exists "admin_read_contact_email_invitation_log" on public.anybike_contact_invitation_email_log;
create policy "admin_read_contact_email_invitation_log"
 on public.anybike_contact_invitation_email_log for select to authenticated
 using ((select auth.uid()) is not null and public.anybike_is_admin());
