      nullif(trim(coalesce(p_website,'')),''),coalesce(p_countries_served,'[]'::jsonb),coalesce(p_ports_served,'[]'::jsonb),
      coalesce(p_services,'[]'::jsonb),nullif(trim(coalesce(p_notes,'')),''),coalesce(p_is_active,true),now(),now()
